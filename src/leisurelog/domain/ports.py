from datetime import date, datetime
from typing import Protocol

from leisurelog.domain.browser import BrowserEvent, BrowserSourceRecord, ResolvedActivity
from leisurelog.domain.daily import DailyActivity
from leisurelog.domain.games import Game
from leisurelog.domain.learned_rules import LearnedRule
from leisurelog.domain.library import ContentIdentity
from leisurelog.domain.models import (
    ActivityEvent,
    Classification,
    IdleEvent,
    IdleSourceRecord,
    Session,
    SourceRecord,
)


class Classifier(Protocol):
    def classify(self, event: ActivityEvent) -> Classification | None: ...


class ActivitySource(Protocol):
    def fetch(
        self, start: datetime, end: datetime, buckets: list[str] | None
    ) -> list[SourceRecord | IdleSourceRecord | BrowserSourceRecord]: ...


class Repository(Protocol):
    def context_candidates(self, rule): ...
    def context_overrides(self, scope=None) -> dict: ...
    def context_rules(self) -> list: ...
    def projects(self) -> list[dict]: ...
    def mark_context_changed(self, event) -> None: ...
    def processing_scope(self, gap_seconds: float): ...
    def clear_changes(self) -> None: ...
    def counts(self) -> dict: ...
    def summary_totals(self) -> dict: ...
    def browser_facts(self) -> dict: ...
    def games(self) -> list[Game]: ...
    def register_content(self, values: list[ContentIdentity]) -> None: ...
    def learned_rules(self) -> list[LearnedRule]: ...
    def unclassified_apps(self, limit: int) -> list[dict]: ...
    def app_event(self, source: str, app: str) -> ResolvedActivity | None: ...
    def save_rule(self, rule: LearnedRule) -> None: ...
    def delete_rule(self, rule_id: str) -> None: ...
    def ingest(self, record: SourceRecord | IdleSourceRecord | BrowserSourceRecord) -> bool: ...
    def events(self, **filters) -> list[ActivityEvent]: ...
    def browser_events(self, **filters) -> list[BrowserEvent]: ...
    def resolved_events(self, **filters) -> list[ResolvedActivity]: ...
    def save_resolved(self, events: list[ResolvedActivity]) -> None: ...
    def prune_resolved(self, scope=None) -> None: ...
    def idle_events(self, **filters) -> list[IdleEvent]: ...
    def timing_overrides(self, scope=None) -> dict[str, str]: ...
    def set_timing_override(self, event_id: str, policy: str | None) -> None: ...
    def overrides(self, scope=None) -> dict[str, Classification | None]: ...
    def set_override(self, event_id: str, value: Classification | None) -> None: ...
    def save_classification(self, event: ActivityEvent) -> None: ...
    def replace_sessions(self, sessions: list[Session], scope=None) -> None: ...
    def replace_daily(self, records: list[DailyActivity], scope=None) -> None: ...
    def range_statistics(
        self, start: date, end: date, granularity: str, purpose: str = "", project_id: str = ""
    ) -> dict: ...
    def sessions(self, **filters) -> list[Session]: ...


class LibraryStore(Protocol):
    def item(self, item_id: str) -> dict: ...
    def alias(self, alias_id: str) -> dict: ...
    def update_item(self, item_id: str, name: str, notes: str) -> None: ...
    def add_alias(self, item_id: str, value: ContentIdentity) -> None: ...
    def merge(self, source_id: str, target_id: str) -> None: ...
    def split(self, alias_id: str) -> str: ...
    def listing(self, query: str, category: str, sort: str, limit: int, offset: int) -> dict: ...
    def detail(self, item_id: str, limit: int, offset: int) -> dict: ...


class GameCatalogStore(Protocol):
    def games(self) -> list[Game]: ...
    def replace(self, payload: dict, games: list[Game]) -> bool: ...
    def status(self) -> dict: ...


class GameStatisticsStore(Protocol):
    def listing(self, query: str, scope: str, sort: str, limit: int, offset: int) -> dict: ...
    def detail(self, key: str, limit: int, offset: int) -> dict: ...


class GamePreferencesStore(Protocol):
    def exists(self, key: str) -> bool: ...
    def save_type(self, key: str, primary: str, tags: list[str]) -> None: ...
    def remove_type(self, key: str) -> None: ...
    def preference_facts(self, start: date, end: date) -> dict: ...
